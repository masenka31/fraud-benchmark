#!/usr/bin/env python
"""Run and render the five-seed Sparkov training-label-delay comparison."""

from __future__ import annotations

import argparse
import json
import platform
import time
from pathlib import Path

import numpy as np

from fraud_benchmark.experiments.experiment import ExperimentConfig
from fraud_benchmark.experiments.experiment import prepare
from fraud_benchmark.experiments.features.util import FEATURE_DIR
from fraud_benchmark.experiments.metrics import best_f1_threshold
from fraud_benchmark.experiments.metrics import score
from fraud_benchmark.experiments.models import fit_xgboost

REGIMES = ('off', 'on', 'slow')
LABELS = {'off': 'No delay', 'on': 'Default delay', 'slow': 'Slow delay'}
RESULTS = {
    'off': Path('results/paper/sparkov_delay_off.json'),
    'on': Path('results/paper/sparkov_delay_on.json'),
    'slow': Path('results/paper/sparkov_delay_slow.json'),
}
DEFAULT_TABLE = Path('results/sparkov_label_delay.md')


def recorded_result(regime: str) -> dict:
    """Read one public paper-result snapshot."""
    return json.loads(RESULTS[regime].read_text())


def _metric(record: dict, partition: str, metric: str) -> str:
    value = record['aggregate'][partition][metric]
    return f'{value["mean"]:.4f} ± {value["sd"]:.4f}'


def _aggregate(seed_records: list[dict]) -> dict:
    return {
        partition: {
            metric: {
                'mean': float(np.mean([row['scores'][partition][metric] for row in seed_records])),
                'sd': float(np.std([row['scores'][partition][metric] for row in seed_records])),
            }
            for metric in ('average_precision', 'precision', 'recall', 'f1')
        }
        for partition in ('val', 'test')
    }


def run_regime(regime: str, seeds: tuple[int, ...], features_dir: Path) -> dict:
    """Fit and score one label regime with validation-only threshold selection."""
    started = time.monotonic()
    prepared = prepare(
        ExperimentConfig(dataset='sparkov', label_delay=regime),
        features_dir,
    )
    seed_records = []
    for seed in seeds:
        fit_started = time.monotonic()
        model = fit_xgboost(
            prepared.x[prepared.train_rows], prepared.y[prepared.train_rows], seed
        )
        val_scores = model.predict_proba(prepared.x[prepared.val_rows])[:, 1]
        test_scores = model.predict_proba(prepared.x[prepared.test_rows])[:, 1]
        threshold = best_f1_threshold(prepared.y_true[prepared.val_rows], val_scores)
        seed_records.append(
            {
                'seed': seed,
                'fit_seconds': round(time.monotonic() - fit_started, 1),
                'scores': {
                    'val': score(prepared.y_true[prepared.val_rows], val_scores, threshold),
                    'test': score(prepared.y_true[prepared.test_rows], test_scores, threshold),
                },
            }
        )
    return {
        'config': {
            'dataset': 'sparkov',
            'model': 'xgboost',
            'label_delay': regime,
            'split': 'standard',
            'seeds': list(seeds),
        },
        'rows': {
            'train': len(prepared.train_rows),
            'val': len(prepared.val_rows),
            'test': len(prepared.test_rows),
        },
        'n_features': len(prepared.names),
        'censored_train_labels': prepared.censored_train_labels,
        'notes': prepared.notes,
        'seeds': seed_records,
        'aggregate': _aggregate(seed_records),
        'total_seconds': round(time.monotonic() - started, 1),
        'python': platform.python_version(),
    }


def render_markdown(records: dict[str, dict]) -> str:
    """Render the publication table from the three canonical records."""
    baseline_ap = records['off']['aggregate']['test']['average_precision']['mean']
    rows = []
    for regime in REGIMES:
        record = records[regime]
        test_ap = record['aggregate']['test']['average_precision']['mean']
        rows.append(
            f'| {LABELS[regime]} | {record["censored_train_labels"]:,} | '
            f'{_metric(record, "val", "average_precision")} | '
            f'{_metric(record, "val", "f1")} | '
            f'{_metric(record, "test", "average_precision")} | '
            f'{_metric(record, "test", "f1")} | {test_ap - baseline_ap:+.4f} |'
        )
    return '\n'.join(
        [
            '# Sparkov synthetic label-delay protocol',
            '',
            'Generated by `scripts/sparkov_delay_protocol.py`; do not edit by hand.',
            '',
            'Entries are mean ± population standard deviation over five XGBoost seeds.',
            'All regimes use the same Sparkov rows, split, features, model settings, and',
            'seeds. Only training-label availability changes; validation and test are',
            'always scored against true labels. The slow regime is a synthetic stress test.',
            '',
            '| Training labels | Hidden train frauds | Validation AP | Validation F1 | '
            'Test AP | Test F1 | Δ test AP |',
            '|---|---:|---:|---:|---:|---:|---:|',
            *rows,
        ]
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--features-dir', type=Path, default=FEATURE_DIR)
    parser.add_argument('--table-out', type=Path, default=DEFAULT_TABLE)
    parser.add_argument('--seeds', type=int, nargs='+', default=[0, 1, 2, 3, 4])
    parser.add_argument(
        '--render-only',
        action='store_true',
        help='regenerate the Markdown table from the latest records without fitting',
    )
    args = parser.parse_args(argv)

    records = {}
    if args.render_only:
        records = {regime: recorded_result(regime) for regime in REGIMES}
    else:
        for regime in REGIMES:
            config = ExperimentConfig(
                dataset='sparkov', label_delay=regime
            )
            config.validate()
            print(f'Running Sparkov label-delay regime: {regime}', flush=True)
            record = run_regime(regime, tuple(args.seeds), args.features_dir)
            records[regime] = record

    for regime, record in records.items():
        RESULTS[regime].parent.mkdir(parents=True, exist_ok=True)
        RESULTS[regime].write_text(json.dumps(record, indent=2, allow_nan=False) + '\n')

    args.table_out.parent.mkdir(parents=True, exist_ok=True)
    args.table_out.write_text(render_markdown(records) + '\n')
    print(f'Wrote {args.table_out}', flush=True)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
